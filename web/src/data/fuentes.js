function fuenteLatin(fuente) {
  if (fuente.startsWith('TA2 ')) return { ...TA2, texto: `${TA2.texto}, término n.º ${fuente.slice(4)}` };
  if (fuente.startsWith('TA98 ')) return TA98(fuente.slice(5));
  if (fuente === 'TNA') return TNA;
  if (fuente === 'compuesto') return { texto: 'Latín formado con términos oficiales (TA98 y Terminologia Neuroanatomica): esta subdivisión no tiene un término propio.', url: TNA.url };
  return { texto: 'Nombre latino de Z-Anatomy (sin término propio en la Terminologia Anatomica).', url: 'https://www.z-anatomy.com/' };
}

